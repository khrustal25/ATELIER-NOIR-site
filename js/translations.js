var LANGUAGE_KEY = "atelier-noir-language";
var currentLanguage = null;
var languageListeners = [];

function getLanguage() {
  if (currentLanguage === "ru" || currentLanguage === "en") return currentLanguage;

  try {
    var saved = localStorage.getItem(LANGUAGE_KEY);
    if (saved === "ru" || saved === "en") return saved;
  } catch (error) {
    /* private mode */
  }

  return document.documentElement.lang === "en" ? "en" : "ru";
}

function t(key) {
  var language = getLanguage();
  var table = translations[language] || translations.ru;
  if (table && Object.prototype.hasOwnProperty.call(table, key)) return table[key];
  if (translations.ru && Object.prototype.hasOwnProperty.call(translations.ru, key)) return translations.ru[key];
  return key;
}

function applyField(element, attribute, key) {
  var value = t(key);
  if (attribute) {
    element.setAttribute(attribute, value);
  } else {
    element.textContent = value;
  }
}

function translatePage() {
  document.documentElement.lang = getLanguage();

  document.querySelectorAll("[data-i18n]").forEach(function (element) {
    applyField(element, null, element.getAttribute("data-i18n"));
  });

  document.querySelectorAll("[data-i18n-aria-label]").forEach(function (element) {
    applyField(element, "aria-label", element.getAttribute("data-i18n-aria-label"));
  });

  document.querySelectorAll("[data-i18n-title]").forEach(function (element) {
    applyField(element, "title", element.getAttribute("data-i18n-title"));
  });

  document.querySelectorAll("[data-i18n-alt]").forEach(function (element) {
    applyField(element, "alt", element.getAttribute("data-i18n-alt"));
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach(function (element) {
    applyField(element, "placeholder", element.getAttribute("data-i18n-placeholder"));
  });

  document.querySelectorAll("[data-i18n-content]").forEach(function (element) {
    applyField(element, "content", element.getAttribute("data-i18n-content"));
  });

  document.querySelectorAll("[data-lang]").forEach(function (button) {
    var active = button.getAttribute("data-lang") === getLanguage();
    button.setAttribute("aria-pressed", active ? "true" : "false");
    if (active) button.setAttribute("aria-current", "true");
    else button.removeAttribute("aria-current");
  });
}

function setLanguage(language) {
  if (language !== "ru" && language !== "en") return getLanguage();

  currentLanguage = language;

  try {
    localStorage.setItem(LANGUAGE_KEY, language);
  } catch (error) {
    /* storage unavailable */
  }

  translatePage();
  languageListeners.forEach(function (listener) {
    listener(language);
  });
  return language;
}

function onLanguageChange(listener) {
  if (typeof listener === "function") languageListeners.push(listener);
}

function initLanguage() {
  document.querySelectorAll("[data-lang]").forEach(function (button) {
    if (button.dataset.i18nBound === "true") return;
    button.dataset.i18nBound = "true";
    button.addEventListener("click", function () {
      setLanguage(button.getAttribute("data-lang"));
    });
  });

  setLanguage(getLanguage());
  document.documentElement.classList.remove("i18n-pending");
}

window.translations = translations;
window.getLanguage = getLanguage;
window.setLanguage = setLanguage;
window.translatePage = translatePage;
window.t = t;
window.onLanguageChange = onLanguageChange;
window.initLanguage = initLanguage;

initLanguage();
